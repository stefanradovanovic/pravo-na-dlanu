/** Each query word may match the term, its explanation or a familiar synonym. */
export function searchReadingTerms(query: string) {
  const words = normalizeSearch(query).split(" ").filter(Boolean);
  return readingTerms.filter((term) => {
    const text = normalizeSearch(`${term.title} ${term.text} ${term.keywords}`);
    return words.every((word) => text.includes(word));
  });
}

import type { InstitutionSource } from "./institution-map";
import { lawSlug } from "./registry-types";
import { normalizeSearch } from "./search";

export type InstitutionProfile = {
  id: string;
  name: string;
  summary: string;
  duties: readonly string[];
  sources: readonly InstitutionSource[];
  keywords?: string;
  mapId?: string;
};

export type InstitutionGroup = {
  id: string;
  title: string;
  description: string;
  source?: InstitutionSource;
  profiles: readonly InstitutionProfile[];
};

function articleSource(
  title: string,
  article: string | number,
): InstitutionSource {
  return {
    title: `${title}, члан ${article}${typeof article === "number" ? "." : ""}`,
    href: `/propisi/${lawSlug(title)}#clan-${normalizeSearch(String(article))}`,
  };
}

const constitution = (article: number) =>
  articleSource("Устав Републике Србије", article);
const ministryLaw = "Закон о министарствима";
const localGovernmentLaw = "Закон о локалној самоуправи";

function ministry(
  id: string,
  name: string,
  article: number | string,
  summary: string,
  duties: readonly string[],
  keywords?: string,
): InstitutionProfile {
  return {
    id,
    name: `Министарство ${name}`,
    summary,
    duties,
    sources: [articleSource(ministryLaw, article)],
    keywords,
  };
}


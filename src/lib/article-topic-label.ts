function topicPhrases(text: string) {
  const phrases: string[][] = [];
  for (const clause of text
    .replace(/\([^()]*\)/gu, " ")
    .replace(reference, " ")
    .replace(
      /(?:^|\s)(?:овог закона|у складу са законом|по правилу|у даљем тексту)(?=\s|[,.!?:;]|$)/giu,
      ", ",
    )
    .split(/[.,;:!?–—*•\n]/u)) {
    let words: string[] = [];
    for (const token of clause.match(
      /[\p{Script=Cyrillic}\p{Script=Latin}-]+/gu,
    ) ?? []) {
      if (breakWords.has(token.toLowerCase())) {
        if (words.length) phrases.push(words);
        words = [];
      } else {
        words.push(token);
      }
    }
    if (words.length) phrases.push(words);
  }
  return phrases;
}

function extractTopic(lead: string): string {
  let best = "";
  let bestScore = -Infinity;
  for (const [index, words] of topicPhrases(lead).entries()) {
    const comparable = words.map((word) => word.toLowerCase());
    for (let start = 0; start < words.length; start++) {
      if (connectors.has(comparable[start]) || generic.has(comparable[start]))
        continue;
      let score = -index * 1.1 - start * 0.65;
      for (let end = start; end < Math.min(words.length, start + 7); end++) {
        const word = comparable[end];
        if (connectors.has(word)) {
          score -= 0.15;
          continue;
        }
        if (generic.has(word)) {
          score -= 0.65;
          continue;
        }
        score += topicWord.test(word) ? 2.4 : 0.95;
        const label = [
          initialNouns.get(comparable[start]) ?? words[start],
          ...words.slice(start + 1, end + 1),
        ].join(" ");
        if (label.length > 76 || !/\p{Script=Cyrillic}/u.test(label)) break;
        const phraseScore =
          score -
          Math.max(0, end - start - 4) * 1.3 -
          (incompleteEnding.test(word) ? 2 : 0);
        if (phraseScore <= bestScore) continue;
        best = label;
        bestScore = phraseScore;
      }
    }
  }
  return best
    ? best[0].toLocaleUpperCase("sr") + best.slice(1)
    : "Текст одредбе";
}

export function articleTopicLabel(lead: string): string {
  return (
    commonTopics.find(([pattern]) => pattern.test(lead))?.[1] ??
    extractTopic(lead)
  );
}

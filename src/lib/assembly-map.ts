import type { InstitutionMap, InstitutionSource } from "./institution-map";

const assemblyRulesPath = "/propisi/poslovnik-narodne-skupstine";

function constitution(article: number): InstitutionSource {
  return {
    title: `Устав, члан ${article}.`,
    href: `/propisi/ustav-republike-srbije#clan-${article}`,
  };
}

function assemblyLaw(article: number): InstitutionSource {
  return {
    title: `Закон о Народној скупштини, члан ${article}.`,
    href: `/propisi/zakon-o-narodnoj-skupstini#clan-${article}`,
  };
}

export function assemblyRulesSource(
  article: number,
  label = `члан ${article}.`,
): InstitutionSource {
  return {
    title: `Пословник Народне скупштине, ${label}`,
    href: `${assemblyRulesPath}#clan-${article}`,
  };
}

